#!/usr/bin/env python3
"""Generate src/vsop87a_data.inc from the official IMCCE VSOP87A files.

Source: Bretagnon & Francou (1988), A&A 202, 309; data files from
https://ftp.imcce.fr/pub/ephem/planets/vsop87/ (VSOP87A.mer ... VSOP87A.nep,
VSOP87A.emb, VSOP87A.ear), stored unmodified in tools/data/vsop87/ and pinned
by SHA-256 below. Every term of every series is emitted (no truncation);
amplitudes, phases and frequencies are copied as decimal text exactly as in
the files.

Run: python3 tools/gen_vsop87a.py > src/vsop87a_data.inc
"""
import hashlib, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'tools', 'data', 'vsop87')
FILES = [  # (suffix, JME body index in the generated table)
    ('mer', 'MERCURY'), ('ven', 'VENUS'), ('ear', 'EARTH'), ('mar', 'MARS'),
    ('jup', 'JUPITER'), ('sat', 'SATURN'), ('ura', 'URANUS'), ('nep', 'NEPTUNE'),
    ('emb', 'EMB'),
]
SHA = {
    'VSOP87A.ear': '69d0b4c7525f094a03099e64558321eb64f2402a478472ee537239bcc59b7cb6',
    'VSOP87A.emb': '992349a8883548a635ad4916023bec8f506e8d3dc8aace8d15964f5e57cab375',
    'VSOP87A.jup': '212bcea552e759fa0a9d732680c05120de2c15d36049b2f6d115ceb25b03d405',
    'VSOP87A.mar': '2c1e9b5cd68276138c2f99506d348e626abe0a5c600b4e50bb588d568b0d13fe',
    'VSOP87A.mer': '01f6f82af31f347fc50affaa920d653e441fc74f2b4738166528adc4c78fa870',
    'VSOP87A.nep': '4ad09bd799336d8f76dcf6f98be57c45d7289db134556c204f098d6bbf888f3a',
    'VSOP87A.sat': '2e72d18684246e2ecd143e35736b45b101cdd06bbcaf2f2502e348c233abff29',
    'VSOP87A.ura': '6fb9626c770eb9972a86050e151cc866e703f503261c79ba0691160e727bf0b9',
    'VSOP87A.ven': 'ecaeceff071db6692820d962ffabfdb7de438db44145bfe0cbcda70f8dbed2a8',
}

def main():
    out = sys.stdout
    out.write('/* Generated by tools/gen_vsop87a.py from the official IMCCE VSOP87A files.\n'
              ' * Do not edit. Bretagnon & Francou (1988), A&A 202, 309.\n'
              ' * Heliocentric rectangular coordinates, ecliptic and equinox J2000 (dynamical),\n'
              ' * au, time in Julian millennia TDB from J2000. All terms included. */\n')
    terms = []
    index = {}  # (body, coord, power) -> (start, count)
    for suffix, body in FILES:
        name = 'VSOP87A.' + suffix
        path = os.path.join(DATA, name)
        raw = open(path, 'rb').read()
        h = hashlib.sha256(raw).hexdigest()
        if h != SHA[name]:
            sys.exit(f'{name}: SHA-256 mismatch {h}')
        out.write(f'/* {name} sha256 {h} */\n')
        cur = None
        for line in raw.decode('ascii').splitlines():
            if not line.strip():
                continue
            if line.lstrip().startswith('VSOP87'):
                f = line.split()
                coord = int(f[f.index('VARIABLE') + 1]) - 1
                power = int(line.split('*T**')[1].split()[0])
                cur = (body, coord, power)
                index[cur] = [len(terms), 0]
                continue
            f = line.split()
            a, b, c = f[-3], f[-2], f[-1]
            terms.append((a, b, c))
            index[cur][1] += 1
    out.write(f'#define JME_VSOP87A_TERM_COUNT {len(terms)}\n')
    out.write('static const double jme_vsop87a_terms[JME_VSOP87A_TERM_COUNT][3] = {\n')
    for a, b, c in terms:
        out.write(f'    {{{a}, {b}, {c}}},\n')
    out.write('};\n')
    out.write('/* [body 0..8: Mercury..Neptune, EMB][coordinate x,y,z][power 0..5] = {start, count} */\n')
    out.write('static const int jme_vsop87a_index[9][3][6][2] = {\n')
    for _, body in FILES:
        out.write('    {\n')
        for coord in range(3):
            row = []
            for power in range(6):
                s, n = index.get((body, coord, power), [0, 0])
                row.append(f'{{{s}, {n}}}')
            out.write('        {' + ', '.join(row) + '},\n')
        out.write('    },\n')
    out.write('};\n')

if __name__ == '__main__':
    main()
