#!/usr/bin/env python3
"""Generate polar-motion certification data, independently of JME.

Inputs (IERS products, freely available):
  finals2000A.all  https://datacenter.iers.org/data/9/finals2000A.all
  eopc04.1962-now  https://hpiers.obspm.fr/iers/eop/eopc04/eopc04.1962-now
Outputs:
  tests/fixtures/eop_finals2000A_excerpt.txt  three 9-day windows, unmodified rows
  tests/fixtures/eop_c04_excerpt.txt          header + one 9-day window, unmodified rows
  tests/fixtures/polar_motion_reference.h     expected values

Expected values:
  xp, yp: 4-point Lagrange interpolation of the excerpt (numpy, written here).
  Observer GCRS position: r_gcrs = C^T r_itrs, where C = eraC2t06a(TT, UT1,
  xp, yp) (IAU 2006/2000A, CIO based) and r_itrs = eraGd2gc(WGS84, lon,
  lat, h). UT1 = TT - DT with DT fixed at 69.184 s (set in the test with
  jme_set_delta_t_userdef), so both sides use the same UT1.
Usage: gen_polar_motion_fixtures.py FINALS C04
"""
import sys
import erfa
import numpy as np

DT = 69.184
WINDOWS = [58849.0, 59580.0, 60310.0]  # 2020-01-01, 2022-01-01, 2024-01-01
C04_WINDOW = 59000.0
SITES = [(-17.88, 28.76, 2396.0), (77.21, 28.61, 216.0), (149.07, -35.32, 580.0), (-70.4, -24.6, 2635.0)]
OFFSETS = [0.0, 0.25, 0.731]


def lagrange4(rows, mjd):
    m = np.array([r[0] for r in rows])
    i = int(np.searchsorted(m, mjd, side="right")) - 1
    idx = range(i - 1, i + 3)
    x = y = 0.0
    for k in idx:
        w = 1.0
        for j in idx:
            if j != k:
                w *= (mjd - m[j]) / (m[k] - m[j])
        x += w * rows[k][1]
        y += w * rows[k][2]
    return x, y


def main():
    finals, c04 = sys.argv[1], sys.argv[2]
    excerpt, rows = [], []
    for line in open(finals):
        mjd = float(line[7:15])
        if any(w - 4 <= mjd <= w + 4 for w in WINDOWS):
            excerpt.append(line.rstrip("\n"))
            rows.append((mjd, float(line[18:27]), float(line[37:46])))
    open("tests/fixtures/eop_finals2000A_excerpt.txt", "w").write("\n".join(excerpt) + "\n")

    cx, crow = [], []
    for line in open(c04):
        if line.startswith("#"):
            if len(cx) < 6:
                cx.append(line.rstrip("\n"))
            continue
        t = line.split()
        if len(t) > 6 and C04_WINDOW - 4 <= float(t[4]) <= C04_WINDOW + 4:
            cx.append(line.rstrip("\n"))
            crow.append((float(t[4]), float(t[5]), float(t[6])))
    open("tests/fixtures/eop_c04_excerpt.txt", "w").write("\n".join(cx) + "\n")

    out = ["/* Generated by tools/gen_polar_motion_fixtures.py (pyerfa %s). */" % erfa.__version__,
           "#define PM_DELTA_T %.3f" % DT,
           "static const struct { double mjd_ut1; double xp; double yp; } pm_interp_reference[] = {"]
    for w in WINDOWS:
        for o in OFFSETS + [-0.6, 1.5]:
            x, y = lagrange4(rows, w + o)
            out.append("    {%.6f, %.17g, %.17g}," % (w + o, x, y))
    out.append("};")
    out.append("static const struct { double mjd_ut1; double xp; double yp; } pm_c04_reference[] = {")
    for o in OFFSETS:
        x, y = lagrange4(crow, C04_WINDOW + o)
        out.append("    {%.6f, %.17g, %.17g}," % (C04_WINDOW + o, x, y))
    out.append("};")
    out.append("static const struct { double jd_tt; double lon; double lat; double alt; double gcrs_km[3]; double gcrs_km_no_pm[3]; } pm_gcrs_reference[] = {")
    for w in WINDOWS:
        for o in OFFSETS:
            ut1 = 2400000.5 + w + o
            tt = ut1 + DT / 86400.0
            x, y = lagrange4(rows, w + o)
            for lon, lat, h in SITES:
                r = erfa.gd2gc(1, np.radians(lon), np.radians(lat), h) / 1000.0
                c = erfa.c2t06a(2400000.5, tt - 2400000.5, 2400000.5, ut1 - 2400000.5,
                                x * erfa.DAS2R, y * erfa.DAS2R)
                c0 = erfa.c2t06a(2400000.5, tt - 2400000.5, 2400000.5, ut1 - 2400000.5, 0.0, 0.0)
                g, g0 = c.T @ r, c0.T @ r
                out.append("    {%.17g, %.2f, %.2f, %.1f, {%.17g, %.17g, %.17g}, {%.17g, %.17g, %.17g}}," %
                           ((tt, lon, lat, h) + tuple(g) + tuple(g0)))
    out.append("};")
    open("tests/fixtures/polar_motion_reference.h", "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
