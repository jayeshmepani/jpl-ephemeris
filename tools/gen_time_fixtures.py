#!/usr/bin/env python3
"""Generate tests/fixtures/time_scales_erfa.h: UTC/TAI/TT/TDB/TCB/TCG reference
values computed with pyerfa (ERFA, the BSD-licensed SOFA derivative), used as an
independent reference for jme_time_scale_convert().

Reference software: pyerfa (tested with 2.0.1.5, ERFA leap table through 2017-01-01).
Run: python3 tools/gen_time_fixtures.py > tests/fixtures/time_scales_erfa.h
Only UTC dates up to 2026 are used so that the ERFA leap table and JME's
table agree (no leap seconds after 2017-01-01).
"""
import erfa

cases = [
    (1960, 1, 1, 0, 0, 10.0), (1965, 1, 1, 7, 12, 0.0), (1968, 2, 1, 12, 0, 0.0),
    (1971, 12, 31, 23, 59, 59.5), (1972, 1, 1, 0, 0, 0.5), (1972, 6, 30, 23, 59, 60.25),
    (1999, 1, 1, 0, 0, 0.0), (2000, 1, 1, 12, 0, 0.0), (2016, 12, 31, 23, 59, 59.0),
    (2016, 12, 31, 23, 59, 60.0), (2016, 12, 31, 23, 59, 60.5), (2017, 1, 1, 0, 0, 0.0),
    (2026, 10, 12, 6, 30, 15.123456),
]
print("/* Generated by tools/gen_time_fixtures.py with pyerfa %s. Do not edit. */" % erfa.__version__)
print("typedef struct { int y, mo, d, h, mi; double s; double utc[2], tai[2], tt[2], tdb[2], tcb[2], tcg[2]; } jme_time_fixture;")
print("static const jme_time_fixture time_fixtures[] = {")
for y, mo, d, h, mi, s in cases:
    u = erfa.dtf2d("UTC", y, mo, d, h, mi, s)
    tai = erfa.utctai(*u)
    tt = erfa.taitt(*tai)
    tdb = erfa.tttdb(*tt, erfa.dtdb(*tt, 0.0, 0.0, 0.0, 0.0))
    tcb = erfa.tdbtcb(*tdb)
    tcg = erfa.tttcg(*tt)
    f = lambda p: "{%r, %r}" % (float(p[0]), float(p[1]))
    print("    {%d, %d, %d, %d, %d, %r, %s, %s, %s, %s, %s, %s}," % (
        y, mo, d, h, mi, s, f(u), f(tai), f(tt), f(tdb), f(tcb), f(tcg)))
print("};")
