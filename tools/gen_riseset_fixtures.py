#!/usr/bin/env python3
"""Generate tests/fixtures/riseset_skyfield.h: rising, setting and meridian
transit times from the JPL DE440s kernel computed with Skyfield (independent
reference), used to certify jme_rise_trans() on the JPL (CALCEPH) path.

Reference software: Skyfield 1.55 (Brandon Rhodes, MIT licence), WGS84
observers, apparent topocentric places (light time, deflection by Sun,
Jupiter, Saturn and the Earth, aberration), IAU 2006/2000A frames, no
refraction, no polar motion. A fixed Delta-T is used (load.timescale(delta_t))
and passed to JME with jme_set_delta_t_userdef, so that both use the same UT1.
Skyfield's almanac events (1 ms search tolerance) are refined here to 1e-11
day by bracketed bisection on Skyfield's own altitude / hour angle.

Events: rise/set of the disc centre at geometric altitude 0 (JME:
JME_RISE_DISC_CENTER | JME_RISE_NO_REFRACTION), upper transit (hour angle 0)
and lower transit (hour angle 12 h), searched forward from jd_start.

Run: python3 tools/gen_riseset_fixtures.py /path/to/de440s.bsp > tests/fixtures/riseset_skyfield.h
"""
import hashlib, sys
import skyfield
from skyfield.api import load, wgs84
from skyfield import almanac

path = sys.argv[1]
digest = hashlib.sha256(open(path, 'rb').read()).hexdigest()
DELTA_T = 69.2
ts = load.timescale(delta_t=DELTA_T)
eph = load(path)
earth = eph['earth']

SITES = [  # lon, lat, height m
    (69.6669, 23.2420, 110.0),      # Bhuj
    (-0.1276, 51.5072, 11.0),       # London
    (151.2093, -33.8688, 58.0),     # Sydney
    (-147.7164, 64.8378, 136.0),    # Fairbanks
    (179.9990, -16.5000, 0.0),      # date line, east side
    (-179.9990, -16.5000, 0.0),     # date line, west side
    (15.6500, 78.2200, 10.0),       # Longyearbyen (polar)
]
BODIES = [(0, 'sun'), (1, 'moon'), (3, 'venus'), (16, 'jupiter barycenter')]
STARTS = [ts.utc(2024, 3, 10), ts.utc(2025, 6, 20, 6), ts.utc(2026, 10, 12)]
RISE, SET, MTRANSIT, ITRANSIT = 1, 2, 4, 8

def refine(f, a, b):
    fa = f(a)
    for _ in range(200):
        if b - a < 1e-11:
            break
        m = 0.5 * (a + b)
        fm = f(m)
        if (fm < 0) == (fa < 0):
            a, fa = m, fm
        else:
            b = m
    return 0.5 * (a + b)

print('/* Generated by tools/gen_riseset_fixtures.py with Skyfield %s from de440s.bsp' % skyfield.__version__)
print(' * (sha256 %s). Delta-T fixed per case. Do not edit. */' % digest)
print('typedef struct { double lon, lat, height; int body; int rsmi; double jd_start, delta_t, jd_event; } jme_riseset_fixture;')
print('static const jme_riseset_fixture riseset_fixtures[] = {')
for lon, lat, h in SITES:
    obs = earth + wgs84.latlon(lat, lon, h)
    for body, name in BODIES:
        target = eph[name]
        alt = lambda jd: obs.at(ts.ut1_jd(jd)).observe(target).apparent().altaz()[0].degrees
        def ha(jd, off):
            v = obs.at(ts.ut1_jd(jd)).observe(target).apparent().hadec()[0].hours - off
            return (v + 12.0) % 24.0 - 12.0
        for t0 in STARTS:
            t1 = ts.ut1_jd(t0.ut1 + 2.0)
            cases = []
            tt, ok = almanac.find_risings(obs, target, t0, t1, horizon_degrees=0.0)
            tt = [t for t, k in zip(tt, ok) if k]
            if len(tt): cases.append((RISE, tt[0].ut1, lambda x: alt(x)))
            tt, ok = almanac.find_settings(obs, target, t0, t1, horizon_degrees=0.0)
            tt = [t for t, k in zip(tt, ok) if k]
            if len(tt): cases.append((SET, tt[0].ut1, lambda x: -alt(x)))
            tt = almanac.find_transits(obs, target, t0, t1)
            if len(tt): cases.append((MTRANSIT, tt[0].ut1, lambda x: ha(x, 0.0)))
            f = almanac.meridian_transits(eph, target, wgs84.latlon(lat, lon, h))
            f.step_days = 0.1
            tt, y = almanac.find_discrete(t0, t1, f)
            lower = [t for t, k in zip(tt, y) if k == 0]
            if lower: cases.append((ITRANSIT, lower[0].ut1, lambda x: ha(x, 12.0)))
            for rsmi, guess, fn in cases:
                e = 2e-7
                while e < 1e-2 and not (fn(guess - e) < 0 <= fn(guess + e)):
                    e *= 2.0
                a, b = guess - e, guess + e
                if not (fn(a) < 0 <= fn(b)):
                    raise SystemExit('bracket failed %s %s %d' % (name, (lon, lat), rsmi))
                jd = refine(fn, a, b)
                t = ts.ut1_jd(jd)
                dt = float((t.tt - t.ut1) * 86400.0)
                print('    {%r, %r, %r, %d, %d, %r, %r, %r},' % (lon, lat, h, body, rsmi, float(t0.ut1), dt, float(jd)))
print('};')
