#!/usr/bin/env python3
"""Generate tests/fixtures/lunar_eclipse_canon.h from the NASA Five Millennium
Catalog of Lunar Eclipses (Espenak & Meeus 2009, NASA TP-2009-214172),
century page 2001-2100: https://eclipse.gsfc.nasa.gov/LEcat5/LE2001-2100.html

Input: tools/data/NASA_LEcat5_2001-2100.txt, the catalog rows exactly as
published (HTML tags removed, one row per eclipse, no values edited).
Fields used: TD of greatest eclipse (whole seconds), gamma, penumbral and
umbral magnitudes (4 decimals), all copied verbatim.
"""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
MON = "JanFebMarAprMayJunJulAugSepOctNovDec"
rows = []
for line in (ROOT / "tools/data/NASA_LEcat5_2001-2100.txt").read_text().splitlines():
    f = line.split()
    if len(f) < 13 or not re.fullmatch(r"\d{5}", f[0]):
        continue
    h, m, s = (int(x) for x in f[4].split(":"))
    rows.append((int(f[1]), MON.index(f[2]) // 3 + 1, int(f[3]), h, m, s, f[8][0], f[10], f[11], f[12]))
out = ["/* Generated by tools/gen_lunar_eclipse_canon_fixtures.py. Source: NASA Five",
       " * Millennium Catalog of Lunar Eclipses (Espenak & Meeus 2009), 2001-2100 page.",
       " * Fields verbatim: year, month, day, TD h m s of greatest eclipse, type,",
       " * gamma, penumbral magnitude, umbral magnitude. */",
       "typedef struct { int y, mo, d, h, mi, s; char type; double gamma, pen_mag, umb_mag; } jme_lunar_canon_fixture;",
       "static const jme_lunar_canon_fixture lunar_canon_fixtures[] = {"]
for r in rows:
    out.append("    { %d, %d, %d, %d, %d, %d, '%s', %s, %s, %s }," % r)
out.append("};")
(ROOT / "tests/fixtures/lunar_eclipse_canon.h").write_text("\n".join(out) + "\n")
print(len(rows), "rows")
