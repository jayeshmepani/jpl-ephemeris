#!/usr/bin/env python3
"""Generate tests/fixtures/deltat_reference.h: independent Delta-T references.

  * IERS: astropy (IERS-A table read from the same tools/data/finals2000A.all),
    TT - UT1 at 0h UTC (table nodes, exact) and at 12h UTC (astropy interpolates
    linearly; JME uses 4-point Lagrange -> compared with a looser tolerance).
  * SMH-2016/2021: Skyfield's Table-S15 splines (Skyfield evaluates the same
    published spline; queried with tt = the JME argument so both use the same y),
    for -720 <= y < 1973 where Skyfield uses S15 unchanged.
  * Espenak-Meeus 2006: re-implemented here from the NASA page with the
    continuous calendar decimal year (Julian calendar before 1582-10-15).

Run: python3 tools/gen_deltat_fixtures.py > tests/fixtures/deltat_reference.h
(needs astropy, skyfield, pyerfa; tools/data/finals2000A.all).
"""
import math, os
import numpy as np
import erfa, astropy, skyfield
from astropy.time import Time
from astropy.utils import iers
from skyfield.api import load

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
finals = os.path.join(root, 'tools', 'data', 'finals2000A.all')
iers.conf.auto_download = False
iers_a = iers.IERS_A.open(finals)
iers.earth_orientation_table.set(iers_a)

def ut1_dt(jd_utc):
    t = Time(jd_utc, format='jd', scale='utc')
    return float((t.tt.jd1 - t.ut1.jd1) * 86400.0 + (t.tt.jd2 - t.ut1.jd2) * 86400.0)

iers_nodes = [2441684.5 + k for k in (0, 1, 1000, 5000, 9862, 10000, 15000, 17000, 19000, 19637)]
iers_noon = [2441685.0 + k for k in (1, 1000, 5000, 9862, 15000, 19000)]

ts = load.timescale(builtin=True)
s15_jd = [2451545.0 + (y - 2000.0) * 365.25 for y in (-719.9, -500.25, -100.0, 0.5, 400.0, 1000.0, 1582.77, 1700.1, 1850.5, 1900.0, 1950.3, 1966.5)]

def jd_julian(y, m, d):
    if m <= 2:
        y -= 1; m += 12
    return math.floor(365.25 * (y + 4716)) + math.floor(30.6001 * (m + 1)) + d - 1524.5

def jd_greg(y, m, d):
    di = int(math.floor(d))
    j1, j2 = erfa.cal2jd(y, m, di)
    return float(j1 + j2) + (d - di)

def year_of(jd):
    # find calendar year containing jd
    if jd < 2299160.5:
        y = int(math.floor((jd - 1721423.5) / 365.25)) + 1
        while jd_julian(y, 1, 1) > jd: y -= 1
        while jd_julian(y + 1, 1, 1) <= jd: y += 1
        return y + (jd - jd_julian(y, 1, 1)) / (jd_julian(y + 1, 1, 1) - jd_julian(y, 1, 1))
    y = int(math.floor((jd - 1721425.5) / 365.2425)) + 1
    while jd_greg(y, 1, 1) > jd: y -= 1
    while jd_greg(y + 1, 1, 1) <= jd: y += 1
    return y + (jd - jd_greg(y, 1, 1)) / (jd_greg(y + 1, 1, 1) - jd_greg(y, 1, 1))

def em2006(y):
    if y < -500: u = (y - 1820) / 100; return -20 + 32 * u * u
    if y < 500:
        u = y / 100
        return 10583.6 - 1014.41*u + 33.78311*u**2 - 5.952053*u**3 - 0.1798452*u**4 + 0.022174192*u**5 + 0.0090316521*u**6
    if y < 1600:
        u = (y - 1000) / 100
        return 1574.2 - 556.01*u + 71.23472*u**2 + 0.319781*u**3 - 0.8503463*u**4 - 0.005050998*u**5 + 0.0083572073*u**6
    if y < 1700: t = y - 1600; return 120 - 0.9808*t - 0.01532*t**2 + t**3/7129
    if y < 1800: t = y - 1700; return 8.83 + 0.1603*t - 0.0059285*t**2 + 0.00013336*t**3 - t**4/1174000
    if y < 1860:
        t = y - 1800
        return 13.72 - 0.332447*t + 0.0068612*t**2 + 0.0041116*t**3 - 0.00037436*t**4 + 0.0000121272*t**5 - 0.0000001699*t**6 + 0.000000000875*t**7
    if y < 1900: t = y - 1860; return 7.62 + 0.5737*t - 0.251754*t**2 + 0.01680668*t**3 - 0.0004473624*t**4 + t**5/233174
    if y < 1920: t = y - 1900; return -2.79 + 1.494119*t - 0.0598939*t**2 + 0.0061966*t**3 - 0.000197*t**4
    if y < 1941: t = y - 1920; return 21.20 + 0.84493*t - 0.076100*t**2 + 0.0020936*t**3
    if y < 1961: t = y - 1950; return 29.07 + 0.407*t - t**2/233 + t**3/2547
    if y < 1986: t = y - 1975; return 45.45 + 1.067*t - t**2/260 - t**3/718
    if y < 2005: t = y - 2000; return 63.86 + 0.3345*t - 0.060374*t**2 + 0.0017275*t**3 + 0.000651814*t**4 + 0.00002373599*t**5
    if y < 2050: t = y - 2000; return 62.92 + 0.32217*t + 0.005589*t**2
    if y < 2150: return -20 + 32*((y-1820)/100)**2 - 0.5628*(2150-y)
    u = (y - 1820) / 100; return -20 + 32*u*u

em_jd = [jd_julian(-1999, 6, 1), jd_julian(-500, 3, 3), jd_julian(-1, 12, 31.5), jd_julian(499, 7, 1), jd_julian(1000, 1, 1),
         jd_julian(1582, 10, 4.5), jd_greg(1582, 10, 15.5), jd_greg(1650, 4, 1), jd_greg(1750, 1, 1), jd_greg(1830, 9, 9),
         jd_greg(1880, 2, 29), jd_greg(1910, 6, 15), jd_greg(1930, 1, 1), jd_greg(1955, 5, 5), jd_greg(1975, 1, 1),
         jd_greg(1995, 7, 1), jd_greg(2026, 10, 12), jd_greg(2100, 1, 1), jd_greg(2500, 1, 1), jd_greg(3000, 12, 31)]

print('/* Generated by tools/gen_deltat_fixtures.py with astropy %s, skyfield %s, pyerfa %s. Do not edit. */'
      % (astropy.__version__, skyfield.__VERSION_STR__ if hasattr(skyfield, '__VERSION_STR__') else '.'.join(map(str, skyfield.VERSION)), erfa.__version__))
