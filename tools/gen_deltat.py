#!/usr/bin/env python3
"""Generate src/deltat_data.inc (Delta-T data tables) from primary data files.

Inputs (kept in tools/data/ with their SHA-256 digests checked below):
  finals2000A.all      IERS Rapid Service/Prediction Centre, Earth orientation
                       data (IERS Bulletin A series, IAU 2000A), downloaded
                       from https://datacenter.iers.org/data/9/finals2000A.all
                       Columns used: MJD (cols 8-15), Bulletin A UT1-UTC flag
                       (col 58, 'I' = IERS observed, 'P' = prediction), Bulletin
                       A UT1-UTC (cols 59-68) and Bulletin B (final, IERS C04)
                       UT1-UTC (cols 155-165). The Bulletin B value is used
                       wherever present (as astropy does), else Bulletin A.
  Table-S15.2016.txt   Stephenson, Morrison & Hohenkerk (2016), Proc. R. Soc. A
                       472: 20160404, official ASCII Table S15 (54 rows,
                       -720.0 .. 2016.0), verbatim; evaluation rule S5.1-S5.3
                       of the electronic supplement.
  Table-S15.2020.csv   Morrison, Stephenson, Hohenkerk & Zawilski (2021),
                       Proc. R. Soc. A 477: 20200776, Table S15 (2020): cubic
                       spline coefficients of Delta-T, -720 .. 2019.

Output tables:
  - jme_deltat_s15[]: {K_i, K_i+1, a0, a1, a2, a3} as published (no rounding).
  - jme_deltat_iers_ut1_tai[]: daily UT1-TAI (s) at 0h UTC from the first to the
    last finals2000A record with a UT1-UTC value. UT1-TAI = (UT1-UTC) - (TAI-UTC)
    is continuous across leap seconds; TAI-UTC is taken from the same leap-second
    list as src/time.c (repeated below and checked against pyerfa when available).
    Values are exact decimal transcriptions (UT1-UTC has 7 decimals).

Run: python3 tools/gen_deltat.py > src/deltat_data.inc
"""
import hashlib, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = os.path.join(root, 'tools', 'data')
FINALS = os.path.join(data, 'finals2000A.all')
S15 = os.path.join(data, 'Table-S15.2020.csv')
S15_2016 = os.path.join(data, 'Table-S15.2016.txt')
S15_2016_SHA = 'b972e922e6a2b666c7fb4baa4014b84818066458a3c3d300d630d991621cd037'
FINALS_SHA = '0baf00f67a39ab362a3e4f07d2a1f084842178523f56bcf5a861e7ac084d411a'

def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()

if sha(FINALS) != FINALS_SHA:
    sys.exit('finals2000A.all SHA-256 mismatch: update FINALS_SHA deliberately after review')

# TAI-UTC since 1972 (IERS Bulletin C); (MJD of first day, TAI-UTC seconds).
LEAPS = [
    (41317, 10), (41499, 11), (41683, 12), (42048, 13), (42413, 14), (42778, 15),
    (43144, 16), (43509, 17), (43874, 18), (44239, 19), (44786, 20), (45151, 21),
    (45516, 22), (46247, 23), (47161, 24), (47892, 25), (48257, 26), (48804, 27),
    (49169, 28), (49534, 29), (50083, 30), (50630, 31), (51179, 32), (53736, 33),
    (54832, 34), (56109, 35), (57204, 36), (57754, 37),
]

def tai_utc(mjd):
    v = None
    for m, d in LEAPS:
        if mjd >= m:
            v = d
    return v

try:
    import erfa
    for mjd in range(41684, 61800, 7):
        y, mo, d, _ = erfa.jd2cal(2400000.5, mjd)
        assert erfa.dat(y, mo, d, 0.0) == tai_utc(mjd), mjd
except ImportError:
    pass

rows = []
for line in open(FINALS):
    if len(line) < 68 or line[57] not in 'IP':
        continue
    mjd = int(float(line[7:15]))
    b = line[154:165].strip() if len(line) >= 165 else ''
    s = b if b else line[58:68].strip()
    rows.append((mjd, line[57], s))
for a, b in zip(rows, rows[1:]):
    assert b[0] == a[0] + 1, (a, b)

from decimal import Decimal
first_mjd = rows[0][0]
last_obs = max(i for i, r in enumerate(rows) if r[1] == 'I')
assert all(r[1] == 'I' for r in rows[:last_obs + 1])

s15 = []
for line in open(S15):
    if line.startswith('#') or line.startswith('K_i'):
        continue
    k0, k1, a3, a2, a1, a0 = line.strip().split(',')
    s15.append((k0, k1, a0, a1, a2, a3))
for a, b in zip(s15, s15[1:]):
    assert float(a[1]) == float(b[0])

if sha(S15_2016) != S15_2016_SHA:
    sys.exit('Table-S15.2016.txt SHA-256 mismatch')
s15_2016 = []
for line in open(S15_2016):
    t = line.split()
    if len(t) == 7 and t[0].isdigit():
        assert int(t[0]) == len(s15_2016) + 1
        s15_2016.append(tuple(t[1:]))
assert len(s15_2016) == 54 and float(s15_2016[0][0]) == -720.0 and float(s15_2016[-1][1]) == 2016.0
for a, b in zip(s15_2016, s15_2016[1:]):
    assert float(a[1]) == float(b[0])

out = sys.stdout
out.write('/* Generated by tools/gen_deltat.py; do not edit. */\n')
out.write('/* finals2000A.all SHA-256 %s */\n' % FINALS_SHA)
out.write('/* Table-S15.2020.csv SHA-256 %s */\n\n' % sha(S15))
out.write('static const double jme_deltat_s15[][6] = {\n')
for r in s15:
    out.write('    {%s},\n' % ', '.join(r))
out.write('};\n\n')
out.write('/* Table-S15.2016.txt SHA-256 %s: SMH 2016 Table S15 as published. */\n' % S15_2016_SHA)
out.write('static const double jme_deltat_s15_2016[][6] = {\n')
for r in s15_2016:
    out.write('    {%s},\n' % ', '.join(r))
out.write('};\n\n')
out.write('#define JME_DELTAT_IERS_FIRST_MJD %d\n' % first_mjd)
out.write('#define JME_DELTAT_IERS_COUNT %d\n' % len(rows))
out.write('#define JME_DELTAT_IERS_LAST_OBSERVED_INDEX %d /* MJD %d; later entries are IERS predictions */\n\n'
          % (last_obs, rows[last_obs][0]))
out.write('/* UT1-TAI (s) at 0h UTC of MJD JME_DELTAT_IERS_FIRST_MJD + i. */\n')
out.write('static const double jme_deltat_iers_ut1_tai[JME_DELTAT_IERS_COUNT] = {\n')
for i in range(0, len(rows), 6):
    chunk = rows[i:i + 6]
    vals = [str(Decimal(s) - tai_utc(m)) for m, f, s in chunk]
    vals = [v if ('.' in v or 'E' in v) else v + '.0' for v in vals]
    out.write('    ' + ', '.join(vals) + ',\n')
out.write('};\n')
