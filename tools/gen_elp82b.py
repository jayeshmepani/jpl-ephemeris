BASE = "https://cdsarc.cds.unistra.fr/ftp/VI/79/"

def load(name, directory):
    if directory:
        data = open(os.path.join(directory, name), "rb").read()
    else:
        data = urllib.request.urlopen(BASE + name, timeout=120).read()
    if hashlib.sha256(data).hexdigest() != SHA256[name]:
        sys.exit("checksum mismatch for " + name)
    return data.decode("ascii").splitlines()[1:]

def ints(s, n):
    return [int(s[3 * i:3 * i + 3]) for i in range(n)]

def main():
    directory = None
    if len(sys.argv) == 3 and sys.argv[1] == "--dir":
        directory = sys.argv[2]
    out = []
    w = out.append
    w("/* Generated by tools/gen_elp82b.py from ELP 2000-82B (Chapront-Touze & Chapront,")
    w(" * CDS VI/79). Do not edit by hand. */")
    for f in range(1, 37):
        name = "ELP%d" % f
        rows = [l for l in load(name, directory) if l.strip()]
        if f <= 3:
            w("static const jme_elp_main_term elp_file_%d[] = {" % f)
            for l in rows:
                il = ints(l, 4)
                c = [l[14:27]] + [l[27 + 12 * k:39 + 12 * k] for k in range(6)]
                w("    {{%d, %d, %d, %d}, {%s}}," % tuple(il + [", ".join(x.strip() for x in c)]))
        elif 10 <= f <= 21:
            w("static const jme_elp_planet_term elp_file_%d[] = {" % f)
            for l in rows:
                il = ints(l, 11)
                pha, x = l[34:43].strip(), l[44:53].strip()
                w("    {{%s}, %s, %s}," % (", ".join(map(str, il)), pha, x))
        else:
            w("static const jme_elp_figure_term elp_file_%d[] = {" % f)
            for l in rows:
                il = ints(l, 5)
                pha, x = l[16:25].strip(), l[26:35].strip()
                w("    {%d, {%d, %d, %d, %d}, %s, %s}," % tuple(il + [pha, x]))
        w("};")
    print("\n".join(out))

main()
