#!/usr/bin/env python3
"""Generate tests/fixtures/laskar1986_reference.h.

Independent evaluation (Python, pyerfa rotations) of Laskar 1986, A&A 157,
59: Table 5 (Earth q, p), Table 8 (p_A, eps_A, NGT column), eq. 35 eps0,
coefficients typed in again from the ADS scans (pp. 64 and 68), and
  P = R1(-eps_A) R3(-(Pi_A + p_A)) R1(pi_A) R3(Pi_A) R1(eps0).
The script also checks the construction itself against ERFA: with the
IAU 2006 angles of eraP06e it must reproduce eraBp06 to 1e-11 over +/-100 yr.
"""
import pathlib, math
import numpy as np, erfa
ROOT = pathlib.Path(__file__).resolve().parent.parent
AS = math.pi / 648000.0
Q = [0, -113469002, 12372674, 12654170, -1371808, -320334, 5072, -6941, 15095, -72, -352]
P = [0, 10180391, 47020439, -5417367, -2507948, 463486, 56431, -50813, -2799, 8609, -67]
PA = [0, 502909.66, 11119.71, 77.32, -2353.16, -180.55, 174.51, 130.95, 24.24, -47.59, -8.66]
EA = [84381.448, -4680.93, -1.55, 1999.25, -51.38, -249.67, -39.05, 7.12, 27.87, 5.79, 2.45]
def poly(c, t): return sum(ck * t ** k for k, ck in enumerate(c))
def rot(ax, a): return erfa.rx(a, np.eye(3)) if ax == 'x' else erfa.rz(a, np.eye(3))
def build(eps0, bpia, pia, pa, epsa):
    return rot('x', -epsa) @ rot('z', -(bpia + pa)) @ rot('x', pia) @ rot('z', bpia) @ rot('x', eps0)
for yrs in (-100, -10, 1, 10, 100):
    jd = 2451545.0 + 365.25 * yrs
    e = erfa.p06e(jd, 0.0)
    m = build(e[0], e[6], e[5], e[12], e[7])
    assert np.abs(m - erfa.bp06(jd, 0.0)[1]).max() < 1e-11, yrs
rows = []
for yrs in (-5000, -2000, -1000, -500, -100, 0, 50, 100, 500, 1000, 2000, 5000):
    jd = 2451545.0 + 365.25 * yrs
    t = yrs / 10000.0
    q, p = poly(Q, t) * 1e-10, poly(P, t) * 1e-10
    m = build(EA[0] * AS, math.atan2(p, q), 2 * math.asin(math.hypot(q, p)), poly(PA, t) * AS, poly(EA, t) * AS)
    rows.append((jd, m))
out = ["/* Generated by tools/gen_laskar1986_fixtures.py (numpy %s, pyerfa %s). */" % (np.__version__, erfa.__version__),
       "typedef struct { double jd; double m[9]; } jme_laskar_fixture;",
       "static const jme_laskar_fixture laskar_fixtures[] = {"]
for jd, m in rows:
    out.append("    { %.1f, { %s } }," % (jd, ", ".join("%.17g" % v for v in m.flatten())))
out.append("};")
(ROOT / "tests/fixtures/laskar1986_reference.h").write_text("\n".join(out) + "\n")
print(len(rows), "rows")
