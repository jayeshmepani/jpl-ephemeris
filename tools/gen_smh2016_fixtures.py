#!/usr/bin/env python3
"""Generate tests/fixtures/deltat_smh2016_reference.h independently of JME.

Source: tools/data/Table-S15.2016.txt, the official ASCII Table S15 of
Stephenson, Morrison & Hohenkerk (2016), Proc. R. Soc. A 472: 20160404.
Evaluation follows the electronic supplement S5 verbatim: choose row i with
K_i <= Y < K_i+1 (equality at the upper end only for Y = 2016.0),
t = (Y - K_i)/(K_i+1 - K_i), DT = a0 + a1 t + a2 t^2 + a3 t^3; outside
-720.0 .. 2016.0 the parabola of eq. (4.1), -320 + 32.5 ((Y - 1825)/100)^2.
Y is the Julian epoch year 2000 + (JD_TT - 2451545)/365.25. Values are exact
rationals rounded once to double.
"""
from fractions import Fraction as F

rows = []
for line in open("tools/data/Table-S15.2016.txt"):
    t = line.split()
    if len(t) == 7 and t[0].isdigit():
        rows.append([F(x) for x in t[1:]])
assert len(rows) == 54


def dt(y):
    for k, (k0, k1, a0, a1, a2, a3) in enumerate(rows):
        if k0 <= y < k1 or (k == len(rows) - 1 and y == k1):
            t = (y - k0) / (k1 - k0)
            return a0 + a1 * t + a2 * t * t + a3 * t * t * t
    u = (y - 1825) / 100
    return F(-320) + F(65, 2) * u * u


years = [F(-1000), F(-720), F(-719, 1) - F(1, 10), F(-500), F(0), F(400), F(999) + F(1, 2), F(1000),
         F(1582), F(1700), F(1855), F(1900), F(1954), F(1990), F(2015), F(2015) + F(9, 10), F(2016),
         F(2016) + F(1, 1000), F(2100)]
print("/* Generated by tools/gen_smh2016_fixtures.py from tools/data/Table-S15.2016.txt. */")
print("static const struct { double jd; double dt; } dt_smh2016_table[] = {")
for y in years:
    jd = F(2451545) + (y - 2000) * F(36525, 100)
    print("    {%r, %r}," % (float(jd), float(dt(y))))
print("};")
