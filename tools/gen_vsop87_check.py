#!/usr/bin/env python3
"""Generate tests/fixtures/vsop87a_check.h from the official IMCCE check file
tools/data/vsop87/vsop87.chk (VSOP87A entries: positions au, velocities au/d).

Run: python3 tools/gen_vsop87_check.py > tests/fixtures/vsop87a_check.h
"""
import os, re, hashlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = os.path.join(ROOT, 'tools', 'data', 'vsop87', 'vsop87.chk')
raw = open(p, 'rb').read()
h = hashlib.sha256(raw).hexdigest()
assert h == 'f8fa52449262be05a22a96840c1acbad0b35c8999e00b5c0477ba8a91a67a51a', h
lines = raw.decode('ascii').splitlines()
bodies = {'MERCURY': 'JME_BODY_MERCURY', 'VENUS': 'JME_BODY_VENUS', 'EARTH': 'JME_BODY_EARTH',
          'MARS': 'JME_BODY_MARS', 'JUPITER': 'JME_BODY_JUPITER', 'SATURN': 'JME_BODY_SATURN',
          'URANUS': 'JME_BODY_URANUS', 'NEPTUNE': 'JME_BODY_NEPTUNE', 'EMB': 'JME_BODY_EARTH_MOON_BARYCENTER', 'EARTH-MOON': 'JME_BODY_EARTH_MOON_BARYCENTER'}
rows = []
num = r'(-?\.?\d*\.?\d+)'
for i, l in enumerate(lines):
    f = l.split()
    if len(f) >= 3 and f[0] == 'VSOP87A':
        body = f[1]
        jd = f[2].replace('JD', '')
        p1 = re.findall(r'[-]?\d*\.\d+', lines[i + 1])
        p2 = re.findall(r'[-]?\d*\.\d+', lines[i + 2])
        rows.append((bodies[body], jd, p1[:3], p2[:3]))
print('/* Generated by tools/gen_vsop87_check.py from IMCCE vsop87.chk (sha256 %s). */' % h)
print('typedef struct { int body; double jd; double pos[3]; double vel[3]; } vsop87a_check_row;')
print('static const vsop87a_check_row vsop87a_check_rows[] = {')
for b, jd, p1, p2 in rows:
    fix = lambda s: s.replace('-.', '-0.') if s.startswith('-.') else ('0' + s if s.startswith('.') else s)
    print('    {%s, %s, {%s}, {%s}},' % (b, jd, ', '.join(map(fix, p1)), ', '.join(map(fix, p2))))
print('};')
