#!/usr/bin/env python3
"""Generate tests/fixtures/star_reference.h: geocentric apparent places of
catalogue stars, used to certify jme_fixstar() (space motion and apparent
place) on the JPL (CALCEPH) path.

Independent reference:
  - space motion: pyerfa 2.0.1.5 eraStarpm (ERFA, BSD-3) from the same
    Hipparcos new-reduction astrometry (van Leeuwen 2007, epoch J1991.25,
    proper motion, parallax) and radial velocity as JME's catalogue, to the
    TDB of each epoch (Skyfield's TT->TDB);
  - apparent place: Skyfield 1.55 (MIT) from the DE440s kernel, the
    propagated star placed at its distance (no further motion): light
    deflection by the Sun, Jupiter and Saturn, annual aberration, GCRS;
  - of-date frame: pyerfa eraPnm06a (IAU 2006/2000A).
Run:
    python3 tools/gen_star_fixtures.py /path/to/de440s.bsp > tests/fixtures/star_reference.h
"""
import hashlib, math, re, sys
import numpy as np
import warnings
import erfa, skyfield

from skyfield.api import load, Star
from skyfield.units import Angle

path = sys.argv[1]
digest = hashlib.sha256(open(path, 'rb').read()).hexdigest()
ts = load.timescale()
eph = load(path)
earth = eph['earth']

# name, HR (the catalogue rows are read from src/fixstar_hipparcos.inc)
STARS = [('HR424', 424), ('Aldebaran', 1457), ('Betelgeuse', 2061), ('Sirius', 2491),
         ('Regulus', 3982), ('HR4730', 4730), ('Spica', 5056), ('Arcturus', 5340),
         ('Antares', 6134), ('Vega', 7001), ('Fomalhaut', 8728),
         # no Hipparcos cross-identification: BSC5 J2000 FK5 position and
         # proper motion, transformed to ICRS with eraFk52h, no parallax
         ('HR545', 545), ('HR596', 596)]
EPOCHS = [2415020.5, 2440587.5, 2448349.0625, 2451545.0, 2459205.25, 2460000.5,
          2466154.75, 2488069.5]

rows = {}
for line in open(__file__.rsplit('/', 2)[0] + '/src/fixstar_hipparcos.inc'):
    m = re.match(r'\s*\{(\d+), (\d+), ([-\d.]+), ([-\d.]+), ([-\d.]+), ([-\d.]+), ([-\d.]+), ([-\d.]+), (\d)\}', line)
    if m:
        rows[int(m.group(1))] = [float(x) for x in m.groups()[2:8]]

fk5 = {}
for line in open(__file__.rsplit('/', 2)[0] + '/src/fixstar_catalog.inc'):
    m = re.match(r'\s*\{(\d+),\s*\d+,\s*\d+,\s*"[^"]*",\s*([-\d.eE+]+),\s*([-\d.eE+]+),\s*([-\d.eE+]+),\s*([-\d.eE+]+)', line)
    if m:
        fk5[int(m.group(1))] = [float(x) for x in m.groups()[1:]]

def c2s_deg(v):
    a, b = erfa.c2s(v)
    return math.degrees(a) % 360.0, math.degrees(b)

print('/* Generated by tools/gen_star_fixtures.py with Skyfield %s and pyerfa %s' % (skyfield.__version__, erfa.__version__))
print(' * from de440s.bsp (sha256 %s). Do not edit. */' % digest)
print('typedef struct { const char *star; double jd_tt; double gcrs[2]; double date[2]; } jme_star_fixture;')
print('static const jme_star_fixture star_fixtures[] = {')
MAS = math.pi / 180.0 / 3.6e6
for name, hr in STARS:
    if hr in rows:
        ra, dec, pma, pmd, plx, rv = rows[hr]
        r1, d1 = math.radians(ra), math.radians(dec)
        pmr1, pmd1, ep1 = pma * MAS / math.cos(d1), pmd * MAS, 2448349.0625
    else:
        ra, dec, pma, pmd = fk5[hr]
        r5, d5 = math.radians(ra), math.radians(dec)
        r1, d1, pmr1, pmd1, _, _ = erfa.fk52h(r5, d5, math.radians(pma / 3600.0) / math.cos(d5),
                                               math.radians(pmd / 3600.0), 0.0, 0.0)
        plx, rv, ep1 = 0.0, 0.0, 2451545.0
    for jd in EPOCHS:
        t = ts.tt_jd(jd)
        tdb = t.tdb
        with warnings.catch_warnings():
            # status 1 (distance overridden) is expected without a parallax;
            # anything else (excessive speed, no convergence) is an error
            warnings.simplefilter('error' if plx > 0.0 else 'ignore', erfa.ErfaWarning)
            r2, d2, _, _, px2, _ = erfa.starpm(r1, d1, pmr1, pmd1, plx / 1000.0, rv,
                                              ep1, 0.0, math.floor(tdb), tdb - math.floor(tdb))
        star = Star(ra=Angle(radians=r2), dec=Angle(radians=d2), parallax_mas=px2 * 1000.0 if plx > 0.0 else 0.0, epoch=t)
        app = earth.at(t).observe(star).apparent()
        v = app.position.au
        g = c2s_deg(v)
        dte = c2s_deg(erfa.pnm06a(jd, 0.0) @ v)
        print('    {"%s", %r, {%r, %r}, {%r, %r}},' % (name, jd, g[0], g[1], dte[0], dte[1]))
print('};')
