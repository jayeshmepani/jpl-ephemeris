#!/usr/bin/env python3
"""Generate tests/fixtures/galcent_reference.h: Galactic Centre 0 Sagittarius
ayanamsa recomputed independently of JME with pyerfa (ERFA, BSD-3).

Definition: ayanamsa = (mean ecliptic longitude of date of Sgr A*) - 240 deg.
Sgr A* position: RA 17h45m40.0409s, Dec -29d00'28.118" (J2000/ICRS frame;
Reid & Brunthaler 2004, ApJ 616, 872, Table 1 note). No proper motion
(see docs/AYANAMSA_MODELS.md).

Two model sets are certified:
  default  : no frame bias, eraPmat76 precession, eraObl80 obliquity.
  IAU2006  : eraEcm06 (bias + IAU 2006 precession + IAU 2006 obliquity).
"""
import erfa
import numpy as np

RA = np.radians((17 + 45 / 60 + 40.0409 / 3600) * 15)
DEC = -np.radians(29 + 28.118 / 3600)
JDS = [625673.5, 1000000.5, 1721057.5, 2086302.5, 2299160.5, 2415020.0,
       2433282.42345905, 2451545.0, 2460000.5, 2488070.0, 2816787.5]


def lon(w):
    return np.degrees(erfa.c2s(w)[0]) % 360.0


def main():
    v = erfa.s2c(RA, DEC)
    out = ["/* Generated by tools/gen_galcent_fixtures.py (pyerfa %s). */" % erfa.__version__,
           "static const struct { double jd; double ayan_default; double ayan_iau2006; } galcent_reference[] = {"]
    for jd in JDS:
        d = lon(erfa.rx(erfa.obl80(jd, 0.0), np.eye(3)) @ erfa.pmat76(jd, 0.0) @ v)
        i = lon(erfa.ecm06(jd, 0.0) @ v)
        out.append("    {%.8f, %.17g, %.17g}," % (jd, (d - 240.0) % 360.0, (i - 240.0) % 360.0))
    out.append("};")
    open("tests/fixtures/galcent_reference.h", "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
