#!/usr/bin/env python3
"""Generate src/fixstar_hipparcos.inc: Hipparcos (2007 new reduction) astrometry
for the Yale Bright Star Catalogue entries used by src/fixstar.c.

Input: tools/data/bsc5_hipparcos2007.csv, produced by the VizieR TAP query
(https://tapvizier.cds.unistra.fr/TAPVizieR/tap/sync, ADQL):

  SELECT b.HR, b.HD, b.RadVel, h.HIP, n.RArad, n.DErad, n.Plx, n.e_Plx, n.pmRA, n.pmDE
  FROM "V/50/catalog" b
  LEFT OUTER JOIN "I/239/hip_main" h ON h.HD=b.HD
  LEFT OUTER JOIN "I/311/hip2" n ON h.HIP=n.HIP

Catalogues: V/50 Yale Bright Star Catalogue 5th ed. (Hoffleit & Warren 1991,
radial velocities); I/239 Hipparcos main catalogue (ESA 1997, HD cross-index);
I/311 Hipparcos, the New Reduction (van Leeuwen 2007, A&A 474, 653):
ICRS positions at epoch J1991.25, mas and mas/yr (pmRA = mu_alpha*cos(delta)).

When one HD maps to several HIP entries the one closest to the BSC J2000
position is kept. Run: python3 tools/gen_fixstar_hipparcos.py > src/fixstar_hipparcos.inc
"""
import csv, math, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bsc = {}
pat = re.compile(r'\{(\d+), (-?\d+), (-?\d+), "((?:[^"\\]|\\.)*)", ([-0-9.e]+), ([-0-9.e]+),')
with open(os.path.join(root, 'src', 'fixstar_catalog.inc')) as f:
    for line in f:
        m = pat.search(line)
        if m:
            bsc[int(m.group(1))] = (float(m.group(5)), float(m.group(6)))

def sep(a1, d1, a2, d2):
    a1, d1, a2, d2 = map(math.radians, (a1, d1, a2, d2))
    c = math.sin(d1) * math.sin(d2) + math.cos(d1) * math.cos(d2) * math.cos(a1 - a2)
    return math.degrees(math.acos(max(-1.0, min(1.0, c))))

best = {}
with open(os.path.join(root, 'tools', 'data', 'bsc5_hipparcos2007.csv')) as f:
    for r in csv.DictReader(f):
        hr = int(r['HR'])
        if not r['HIP'] or not r['RArad'] or hr not in bsc:
            continue
        ra, de = float(r['RArad']), float(r['DErad'])
        d = sep(ra, de, *bsc[hr])
        if d > 0.05:  # > 3 arcmin: cross-identification not trusted
            continue
        if hr not in best or d < best[hr][0]:
            best[hr] = (d, r)

print('/* Generated by tools/gen_fixstar_hipparcos.py from tools/data/bsc5_hipparcos2007.csv.')
print(' * Hipparcos new reduction (van Leeuwen 2007; VizieR I/311), ICRS, epoch J1991.25;')
print(' * radial velocity from the Yale BSC5 (VizieR V/50). Do not edit by hand. */')
print('static const jme_star_hip_entry star_hipparcos[] = {')
for hr in sorted(best):
    r = best[hr][1]
    rv = r['RadVel'] if r['RadVel'] else '0'
    has_rv = 1 if r['RadVel'] else 0
    plx = float(r['Plx']) if r['Plx'] else 0.0
    print('    {%d, %s, %.8f, %.8f, %.2f, %.2f, %.2f, %s, %d},' % (
        hr, r['HIP'], float(r['RArad']), float(r['DErad']),
        float(r['pmRA'] or 0), float(r['pmDE'] or 0), plx, float(rv), has_rv))
print('};')
print('/* %d of %d BSC entries matched. */' % (len(best), len(bsc)), file=sys.stderr)
