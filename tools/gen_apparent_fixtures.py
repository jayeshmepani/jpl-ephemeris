#!/usr/bin/env python3
"""Generate tests/fixtures/apparent_skyfield.h: geocentric apparent places from
the JPL DE440s kernel computed with independent reference software, used to
certify the JPL (CALCEPH) path of jme_calc().

Reference software (tested versions): Skyfield 1.55 (Brandon Rhodes, MIT
licence) for light time, gravitational deflection and annual aberration
(GCRS apparent place); pyerfa 2.0.1.5 (ERFA, BSD-3) for the IAU 2006/2000A
bias-precession-nutation matrix (eraPnm06a), the IAU 2006 mean obliquity
(eraObl06) and IAU 2006/2000A nutation (eraNut06a).

Kernel: de440s.bsp from https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/
(its SHA-256 is recorded in the generated header). Run:
    python3 tools/gen_apparent_fixtures.py /path/to/de440s.bsp > tests/fixtures/apparent_skyfield.h

Values: TT Julian date, JME body id, then
  gcrs:  apparent RA, Dec (deg) in GCRS axes and light-time distance (au);
  j2000: apparent RA, Dec (deg) on the mean equator and equinox of J2000
         (GCRS vector rotated by the IAU 2006 frame bias, eraBp06);
  date:  apparent RA, Dec (deg) on the true equator and equinox of date;
  ecl:   apparent longitude, latitude (deg) on the true ecliptic of date
         (IAU 2006 mean obliquity + nutation in obliquity).
The generator also checks that Skyfield's own of-date place agrees with the
ERFA matrix to 0.2 mas.
"""
import hashlib, math, sys
import numpy as np
import erfa, skyfield
from skyfield.api import load

path = sys.argv[1]
digest = hashlib.sha256(open(path, 'rb').read()).hexdigest()

BODIES = [(0, 'sun'), (1, 'moon'), (2, 'mercury'), (3, 'venus'),
          (15, 'mars barycenter'), (16, 'jupiter barycenter'), (17, 'saturn barycenter'),
          (18, 'uranus barycenter'), (19, 'neptune barycenter'), (20, 'pluto barycenter')]
EPOCHS = [2396770.5, 2415020.31352, 2433282.4235, 2440587.5, 2451545.0,
          2451545.000001, 2455197.5, 2460000.5, 2460676.25, 2466154.75,
          2488069.5, 2506321.5]

ts = load.timescale()
eph = load(path)
earth = eph['earth']

def c2s_deg(v):
    a, b = erfa.c2s(v)
    return math.degrees(a) % 360.0, math.degrees(b)

print('/* Generated by tools/gen_apparent_fixtures.py with Skyfield %s and pyerfa %s' % (skyfield.__version__, erfa.__version__))
print(' * from de440s.bsp (sha256 %s). Do not edit. */' % digest)
print('typedef struct { double jd_tt; int body; double gcrs[3]; double j2000[2]; double date[2]; double ecl[2]; } jme_apparent_fixture;')
print('static const jme_apparent_fixture apparent_fixtures[] = {')
for jd in EPOCHS:
    t = ts.tt_jd(jd)
    rnpb = erfa.pnm06a(jd, 0.0)
    rb = erfa.bp06(jd, 0.0)[0]
    dpsi, deps = erfa.nut06a(jd, 0.0)
    eps = erfa.obl06(jd, 0.0) + deps
    rx = np.array([[1, 0, 0], [0, math.cos(eps), math.sin(eps)], [0, -math.sin(eps), math.cos(eps)]])
    for body, name in BODIES:
        app = earth.at(t).observe(eph[name]).apparent()
        v = app.position.au
        ra0, de0, dist = app.radec()
        w = rnpb @ v
        rd, dd = c2s_deg(w)
        rj, dj = c2s_deg(rb @ v)
        lo, la = c2s_deg(rx @ w)
        sra, sde, _ = app.radec('date')
        dra = ((sra._degrees - rd + 180) % 360 - 180) * math.cos(math.radians(dd)) * 3.6e6
        if abs(dra) > 0.2 or abs(sde.degrees - dd) * 3.6e6 > 0.2:
            raise SystemExit('Skyfield/ERFA of-date disagreement at %r %s' % (jd, name))
        print('    {%r, %d, {%r, %r, %r}, {%r, %r}, {%r, %r}, {%r, %r}},' % (
            jd, body, float(ra0._degrees), float(de0.degrees), float(dist.au), rj, dj, rd, dd, lo, la))
print('};')
